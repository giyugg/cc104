package StringPractice20260318.DemoFiles;

public class AD_LengthMethod {
    static void main(String[] args) {
        String str = "Microsoft"; // 9
        String str2 = "Google"; // 6
        String str3 = "Apple"; // 5

        // + operator is used to concatenate two or more strings.
        String str4 = str + str2 + str3; // Sums Str 1 2 and 3.

        System.out.println(str.length());
        System.out.println(str2.length());
        System.out.println(str3.length());
        System.out.println(str4.length());
    }
}
